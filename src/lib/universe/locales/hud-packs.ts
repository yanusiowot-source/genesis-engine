import type { Copy } from "../i18n";
import type { DeepPartial } from "../copy-merge.ts";

type HudIn = {
  clock: string;
  evolve: string;
  evolving: string;
  now: string;
  collide: string;
  spark: string;
  dawn: string;
  stars: string;
  end: string;
  glow: string;
  dark: string;
  fade: string;
  holes: string;
  last: string;
  star: string;
  unstar: string;
  install: string;
  siliconOpen: string;
  eternalOpen: string;
  skies: string;
};

function hud(p: HudIn): DeepPartial<Copy> {
  return {
    star: p.star,
    unstar: p.unstar,
    install: p.install,
    siliconOpen: p.siliconOpen,
    eternalOpen: p.eternalOpen,
    skies: p.skies,
    obs: {
      clock: p.clock,
      evolve: p.evolve,
      evolving: p.evolving,
      now: p.now,
      collide: p.collide,
      epochs: {
        inflation: p.spark,
        recombination: p.glow,
        darkAges: p.dark,
        reionization: p.dawn,
        stellar: p.stars,
        degeneracy: p.fade,
        blackHoles: p.holes,
        heatDeath: p.last,
      },
      jumps: {
        inflation: p.spark,
        reionization: p.dawn,
        stellar: p.stars,
        heatDeath: p.end,
      },
    },
  };
}

